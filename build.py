#!/usr/bin/env python3
"""
Bundle all course Markdown files into course-data.js so index.html works
when opened directly from disk (file://), where browsers block fetch().

Usage:  python3 build.py
(c) 2026 Manikarnika Technologies - manikarnikatechnologies.in
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent


def main() -> None:
    files = {}
    for path in [ROOT / "README.md", *sorted((ROOT / "modules").glob("*.md")), *sorted((ROOT / "appendix").glob("*.md"))]:
        if path.exists():
            files[path.relative_to(ROOT).as_posix()] = path.read_text(encoding="utf-8")

    js = (
        "/* Auto-generated by build.py. Do not edit; edit the .md files and re-run build.py. */\n"
        "/* (c) 2026 Manikarnika Technologies - manikarnikatechnologies.in */\n"
        "window.COURSE_FILES = " + json.dumps(files, ensure_ascii=False, indent=0) + ";\n"
    )
    (ROOT / "course-data.js").write_text(js, encoding="utf-8")
    print(f"Bundled {len(files)} files into course-data.js")

    import seo  # static, crawlable lesson pages for search engines
    seo.build()


if __name__ == "__main__":
    main()
